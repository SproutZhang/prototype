export function getScenarioWorkflowMeta(workflowKey: string): ScenarioWorkflowMeta | undefined {
  return SCENARIO_WORKFLOW_META[workflowKey]
}

export function getScenarioTraceRecords(workflowKey: string): AiTraceRecord[] {
  const fromScenario = SCENARIO_TRACE_RECORDS.filter((record) => record.workflowKey === workflowKey)
  const fromGlobal = AI_TRACE_RECORDS.filter((record) => record.workflowKey === workflowKey)
  const merged = [...fromScenario, ...fromGlobal]
  return merged.sort(
    (a, b) => new Date(b.occurredAt).getTime() - new Date(a.occurredAt).getTime(),
  )
}

export function findInitialTraceId(records: AiTraceRecord[], sessionId?: string): string {
  if (sessionId) {
    const match = records.find((record) => record.sessionId === sessionId)
    if (match) return match.id
  }
  return records[0]?.id ?? ''
}
